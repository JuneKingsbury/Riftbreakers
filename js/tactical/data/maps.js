// Map definitions. Each map has:
//   width, height   — grid dimensions
//   tiles           — array of strings (one per row, one char per tile)
//   elevation       — array of strings (one per row, one digit per tile 0-3)
//   playerSpawns    — six {x,y} for the player party (north-west, or north for the pass)
//   enemySpawns     — six {x,y} for the enemy side (south-east, or south for the pass)
//
// Tile chars:  . grass  , dirt  ~ water  # wall  : rubble  ^ high
//
// Maps have no perimeter wall: the terrain simply ends at the edge. Every spawn can reach
// every other spawn (tests/tactical/map-and-movement.test.mjs checks this).

function grid(str) {
    return str.split('\n').map(r => r.trimEnd()).filter(r => r.length > 0);
}

