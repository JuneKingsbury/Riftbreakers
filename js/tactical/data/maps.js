// Map definitions. Each map has:
//   width, height   — grid dimensions
//   tiles           — array of strings (one per row, one char per tile)
//   elevation       — array of strings (one per row, one digit per tile 0-3)
//   playerSpawns    — [{x,y},...] for player units (left/top side)
//   enemySpawns     — [{x,y},...] for enemy units (right/bottom side)
//
// Tile chars:  . grass  , dirt  ~ water  # wall  : rubble  ^ high

function grid(str) {
    return str.split('\n').map(r => r.trimEnd()).filter(r => r.length > 0);
}

