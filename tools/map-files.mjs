// Reading and writing map files under js/tactical/data/maps. Shared by the dev server and
// the conversion script. The game itself only imports the generated index.js.
import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

/** Map ids in a maps directory, sorted so MAP_DATA has a stable order. */
export function listMapIds(dir) {
    return readdirSync(dir).filter(f => f.endsWith('.json')).map(f => f.slice(0, -5)).sort();
}

/** Regenerates index.js, which imports every map file and exports MAP_DATA. */
export function writeMapIndex(dir) {
    const ids = listMapIds(dir);
    const ident = id => 'm_' + id;
    const lines = [
        '// Generated by tools/map-files.mjs (the dev server rewrites it when a map is saved).',
        '// Do not edit by hand: add or remove .json files in this folder instead.',
        ...ids.map(id => `import ${ident(id)} from './${id}.json' with { type: 'json' };`),
        '',
        `export const MAP_DATA = [${ids.map(ident).join(', ')}];`,
        '',
    ];
    writeFileSync(path.join(dir, 'index.js'), lines.join('\n'));
    return ids;
}

/** Map file text: one map row per line so files stay readable in diffs. */
export function formatMapJson(json) {
    const { columns, ...rest } = json;
    const rows = [];
    for (let y = 0; y < json.depth; y++) {
        rows.push('    ' + columns.slice(y * json.width, (y + 1) * json.width).map(c => JSON.stringify(c)).join(','));
    }
    const spawns = list => '[\n' + list.map(s => '    ' + JSON.stringify(s)).join(',\n') + '\n  ]';
    const head = Object.entries(rest).map(([k, v]) =>
        `  ${JSON.stringify(k)}: ${k.endsWith('Spawns') ? spawns(v) : JSON.stringify(v)}`);
    return `{\n${head.join(',\n')},\n  "columns": [\n${rows.join(',\n')}\n  ]\n}\n`;
}
