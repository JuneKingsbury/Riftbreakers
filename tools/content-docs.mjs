// Writes js/content/CONTENT.md: a reference of every value content may use (stats, statuses,
// elements, equipment types...), the abilities items can grant, every field of every kind of
// content, and an index of what the game holds. Run after changing content or vocab.js:
//   npm run content-docs
import { writeFileSync } from 'node:fs';

import * as V from '../js/content/vocab.js';
import { ABILITY_FILE } from '../js/content/abilities.js';
import { ABILITIES, PROMOTES_FROM } from '../js/tactical/data-registry.js';
import { JOB_DATA } from '../js/content/jobs.js';
import { EQUIPMENT } from '../js/tactical/data/equipment.js';
import { RELICS } from '../js/run/data/relics.js';
import { AFFIXES } from '../js/content/affixes.js';
import { REALMS, CHAINS, ACT_REALMS } from '../js/run/data/realms.js';
import { ENCOUNTERS } from '../js/run/data/encounters.js';
import { EVENTS } from '../js/run/data/events.js';

const out = [];
const h = (level, text) => out.push('', `${'#'.repeat(level)} ${text}`, '');
const table = (head, rows) => {
    out.push(`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`);
    for (const r of rows) out.push(`| ${r.map(c => String(c ?? '').replace(/\|/g, '\\|')).join(' | ')} |`);
};
const code = (s) => `\`${s}\``;
const title = (k) => k.replace(/_/g, ' ').replace(/\b\w/g, c => c.toUpperCase());

out.push('# Riftbreak content reference',
    '',
    'Generated by `npm run content-docs` from `js/content/vocab.js` and the content itself. Do not edit by hand.',
    'How to add content: [README.md](README.md).');

h(2, 'Stats');
table(['Key', 'Label', 'On items', 'In statMods', 'Buffable', 'Meaning'], Object.entries(V.STATS).map(([k, s]) => [
    code(k), s.short, V.ITEM_STATS.includes(k) ? 'yes' : '', V.MOD_STATS.includes(k) ? 'yes' : '', V.BUFF_STATS.includes(k) ? 'yes' : '', s.desc]));
out.push('', '`statMods` covers relics, event rewards (`memberStatMods`), enemy roster entries and summons (`summonMods`).');

h(2, 'Status effects');
out.push('Any of these can be inflicted (`applyStatus`, `attackProc`, `attackerStatus`, `onMove.enemiesStatus`) or granted (`selfStatus`, relic `battleStart`). Cures remove the harmful ones.', '');
table(['Key', 'Name', 'Kind', 'Effect', 'Inflicted by'], Object.entries(V.STATUSES).map(([k, s]) => [
    code(k), s.name, s.harmful ? 'harmful' : 'helpful', s.desc,
    Object.keys(ABILITIES).filter(a => !a.includes('@') && ABILITIES[a].applyStatus === k).map(a => ABILITIES[a].name).join(', ')]));
h(3, 'Engine states');
out.push('Set by the engine, not by content (except `defend`, which a reaction can grant with `selfStatus`). Tactics scripts can check them.', '');
table(['Key', 'Name', 'Meaning'], Object.entries(V.ENGINE_STATES).map(([k, s]) => [code(k), s.name, s.desc]));

h(2, 'Elements and schools');
table(['Element', 'Name'], Object.entries(V.ELEMENTS).map(([k, n]) => [code(k), n]));
out.push('');
table(['School', 'Name', 'Classes'], Object.entries(V.SCHOOLS).map(([k, n]) => [code(k), n,
    Object.keys(JOB_DATA).filter(j => JOB_DATA[j].tier && JOB_DATA[j].schools?.includes(k)).map(title).join(', ')]));

h(2, 'Equipment');
table(['Slot', 'Appearance field', 'Items'], Object.entries(V.EQUIP_SLOTS).map(([k, s]) => [code(k), code(s.field),
    Object.values(EQUIPMENT).filter(i => i.slot === k).length]));
out.push('');
table(['Type', 'Slots', 'Worn by (starting classes)', 'Meaning'], Object.entries(V.EQUIP_TYPES).map(([k, t]) => [code(k), t.slots.join(', '),
    ['boots', 'trinket'].includes(k) ? 'everyone' : Object.keys(JOB_DATA).filter(j => JOB_DATA[j].tier === 1 && Object.values(JOB_DATA[j].allowedEquipment ?? {}).flat().includes(k)).map(title).join(', '),
    t.desc]));
out.push('', `Item rarities: ${V.ITEM_RARITIES.map(code).join(', ')}. Relic rarities: ${V.RARITIES.map(code).join(', ')}.`);

h(2, 'Abilities items can grant');
out.push('An item\'s `grants` takes action abilities (they join the wearer\'s skill list); `grantsPassive` takes reaction, support and movement abilities (always on while worn). Any ability of the right slot works.', '');
const base = Object.keys(ABILITIES).filter(k => !k.includes('@') && k !== 'attack');
const grantedBy = (k) => Object.entries(EQUIPMENT).filter(([, i]) => i.grants?.includes(k) || i.grantsPassive?.includes(k)).map(([, i]) => i.name);
for (const [field, slots] of Object.entries(V.ITEM_GRANT_SLOTS)) {
    h(3, `${code(field)}: ${slots.join(', ')}`);
    table(['Key', 'Name', 'Slot', 'Defined in', 'On items now'], base.filter(k => slots.includes(ABILITIES[k].slot ?? 'action'))
        .sort((a, b) => (ABILITIES[a].slot ?? '').localeCompare(ABILITIES[b].slot ?? '') || ABILITIES[a].name.localeCompare(ABILITIES[b].name))
        .map(k => [code(k), ABILITIES[k].name, ABILITIES[k].slot ?? 'action', ABILITY_FILE[k], grantedBy(k).join(', ')]));
}

h(2, 'Fields');
out.push('Every field each kind of content may have. `validate.js` rejects anything else.');
const typeOf = (spec) => {
    switch (spec.type) {
        case 'enum': return spec.values.map(v => code(v)).join(' / ');
        case 'ref': return `${spec.of} key`;
        case 'list': return `list of ${typeOf(spec.of)}`;
        case 'map': return spec.keys ? `{ ${spec.keys.join(', ')} } → ${typeOf(spec.of)}` : `key → ${typeOf(spec.of)}`;
        case 'object': return `{ ${Object.keys(spec.fields).join(', ')} }`;
        default: return spec.type;
    }
};
const fieldRows = (fields, prefix = '') => Object.entries(fields).flatMap(([k, spec]) => [
    [code(prefix + k) + (spec.required ? ' *' : ''), typeOf(spec), spec.desc],
    ...(spec.type === 'object' ? fieldRows(spec.fields, `${prefix}${k}.`) : []),
    ...(spec.type === 'list' && spec.of.type === 'object' ? fieldRows(spec.of.fields, `${prefix}${k}[].`) : []),
]);
const WHERE = { ability: 'classes/, enemies/, items/abilities.js, abilities/', job: 'classes/ (`job`), enemies/ (`jobs`)', item: 'items/<slot>.js', relic: 'relics.js', affix: 'affixes.js', event: 'events.js, realms/<realm>.js (`events`)', encounter: 'realms/<realm>.js (`encounters`)', realm: 'realms/<realm>.js (`realm`)' };
for (const [kind, fields] of Object.entries(V.SCHEMAS)) {
    h(3, `${title(kind)} (${WHERE[kind]})`);
    table(['Field', 'Type', 'Meaning'], fieldRows(fields));
}
out.push('', '`*` required.');

h(2, 'What the game holds');
h(3, 'Classes');
table(['Class', 'Tier', 'Schools', 'Promotes into / from', 'Unlock', 'Role'], Object.entries(JOB_DATA).filter(([, j]) => j.tier).map(([k, j]) => [
    title(k), j.tier, (j.schools ?? []).map(title).join(' + '), j.tier === 1 ? j.promotions.map(title).join(', ') : (PROMOTES_FROM[k] ?? []).map(title).join(', '),
    j.unlock ? `${j.unlock.type} #${j.unlock.order}` : '', j.role ?? '']));
h(3, 'Realms');
table(['Realm', 'Chain (tier)', 'Acts', 'Draws', 'Fights (normal/elite/boss)', 'Bosses', 'Events'], Object.values(REALMS).map(r => [
    `${r.name} (${code(r.id)})`, `${CHAINS[r.chain].name} (${r.tier})`,
    Object.entries(ACT_REALMS).filter(([, ids]) => ids.includes(r.id)).map(([a]) => a).join(', ')
        || `drawn by ${Object.values(REALMS).find(o => o.draws?.includes(r.id))?.name ?? 'nothing'}`,
    (r.draws ?? []).map(d => REALMS[d].name).join(', '),
    ['normal', 'elite', 'boss'].map(k => ENCOUNTERS[r.id][k]?.length ?? 0).join(' / '),
    (r.bosses ?? []).map(b => Object.values(ENCOUNTERS).flatMap(z => z.boss ?? []).find(d => d.id === b)?.name ?? b).join(', '),
    EVENTS.filter(e => e.realms?.includes(r.id)).length]));
h(3, 'Enemies');
const usedBy = (job) => Object.values(ENCOUNTERS).flatMap(z => Object.values(z).flat()).filter(e => e.roster.some(x => x.job === job)).length;
table(['Job', 'HP', 'ATK', 'MAT', 'SPD', 'Abilities', 'In fights'], Object.entries(JOB_DATA).filter(([, j]) => !j.tier).map(([k, j]) => [
    code(k), j.maxHp, j.atk, j.mat, j.spd, (j.abilities ?? []).join(', '), usedBy(k)]));
h(3, 'Relics');
table(['Relic', 'Rarity', 'Effect'], Object.values(RELICS).map(r => [r.name, r.rarity, r.desc]));
h(3, 'Elite affixes');
table(['Affix', 'Acts', 'Effect'], Object.values(AFFIXES).map(a => [a.name, (a.acts ?? [1, 2, 3, 4]).join(', '), a.desc]));
out.push('', `Items: ${Object.keys(EQUIPMENT).length}. Abilities: ${base.length + 1}. Events: ${EVENTS.length} (${EVENTS.filter(e => e.realms).length} realm events).`, '');

writeFileSync(new URL('../js/content/CONTENT.md', import.meta.url), out.join('\n'));
console.log('wrote js/content/CONTENT.md');
